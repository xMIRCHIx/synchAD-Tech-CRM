import { NextResponse } from 'next/server'

const GEMINI_API_KEY = process.env.GEMINI_API_KEY

interface ChatMessage {
  role: 'user' | 'assistant'
  content: string
}

export async function POST(req: Request) {
  try {
    const { message, history = [], targetWebsiteTypes = ['none', 'broken'] } = await req.json()

    if (!message || typeof message !== 'string') {
      return NextResponse.json({ error: 'Message is required' }, { status: 400 })
    }

    if (!GEMINI_API_KEY) {
      return NextResponse.json(
        { error: 'GEMINI_API_KEY is not configured in .env.local' },
        { status: 500 }
      )
    }

    const systemPrompt = `You are "LeadGen AI Copilot" — an elite autonomous B2B Lead Generation & WhatsApp Outreach Strategist built directly into this CRM.
You assist agency owners, freelancers, and growth teams in finding high-paying local business clients in India & worldwide.

Key Capabilities:
1. You answer any question about B2B growth, local niches (Dentists, Doctors, Gyms, Cafes, Spas, Real Estate, Salons, Tuition Centers, Lawyers, etc.), cold WhatsApp outreach hooks, pricing strategies, and local lead gen.
2. You can CREATE / PROPOSE new scraping campaigns based on the user's natural language request (in Hindi, Hinglish, or English).

Important Rules for Campaign Creation:
- If the user wants to create, launch, or build a campaign (e.g. "Mumbai me dentists ke bina website wale campaign bana do", "Delhi cafes with broken sites", "create campaign for gym owners in Bangalore"):
- You MUST generate a structured campaign plan and include a JSON object at the very end of your response inside a \`\`\`json\`\`\` code block with this exact schema:
\`\`\`json
{
  "isCampaignProposal": true,
  "campaign": {
    "name": "Creative descriptive campaign name (e.g. Dental Clinics Mumbai - No Website)",
    "niche": "Target Niche category (e.g. Dentists & Dental Clinics)",
    "searchQuery": "Google Maps search query (e.g. dental clinics)",
    "location": "City and Country (e.g. Mumbai, India)",
    "maxLeads": 40,
    "targetWebsiteTypes": ["none", "broken"]
  }
}
\`\`\`
- Note for "targetWebsiteTypes":
  - Values can be: "none" (businesses without website on Maps), "broken" (broken/offline sites), "exists" (has active website).
  - Default to ["none", "broken"] when the user asks for non-website / broken website leads, as these are highest-converting for web design/WhatsApp agencies.
  - If user wants all leads, set ["none", "broken", "exists"].
- If the user is just asking a question (not creating a campaign), respond with friendly, sharp, insightful advice in the user's language (Hindi / Hinglish / English), without the proposal JSON block.
- Always be encouraging, strategic, and concise.`

    // Format contents for Gemini API
    const contents: any[] = []

    // Add prior conversation history
    for (const msg of history.slice(-8)) {
      contents.push({
        role: msg.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: msg.content }]
      })
    }

    // Add latest user message
    contents.push({
      role: 'user',
      parts: [
        {
          text: `[User Instruction]: ${message}\n[Current Selected Website Filter Preference]: ${JSON.stringify(
            targetWebsiteTypes
          )}`
        }
      ]
    })

    const candidateModels = ['gemini-3.5-flash-lite', 'gemini-flash-lite-latest', 'gemini-3.8-flash']
    let rawText = ''
    let lastError: any = null

    for (const model of candidateModels) {
      try {
        const geminiRes = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${GEMINI_API_KEY}`,
          {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              systemInstruction: {
                parts: [{ text: systemPrompt }]
              },
              contents,
              generationConfig: {
                temperature: 0.4,
                maxOutputTokens: 1200
              }
            }),
            signal: AbortSignal.timeout(18000)
          }
        )

        if (geminiRes.ok) {
          const geminiData = await geminiRes.json()
          rawText = geminiData.candidates?.[0]?.content?.parts?.[0]?.text || ''
          if (rawText) break
        } else {
          const errText = await geminiRes.text()
          lastError = new Error(`Gemini ${model} returned ${geminiRes.status}: ${errText}`)
        }
      } catch (err: any) {
        lastError = err
      }
    }

    if (!rawText) {
      throw lastError || new Error('No response generated by Gemini AI models.')
    }

    // Check if response contains a campaign proposal JSON block
    let proposalData: any = null
    const jsonMatch = rawText.match(/```(?:json)?\s*([\s\S]*?)\s*```/)

    let cleanText = rawText
    if (jsonMatch) {
      try {
        const parsed = JSON.parse(jsonMatch[1])
        if (parsed.isCampaignProposal && parsed.campaign) {
          proposalData = parsed.campaign
          // Remove the raw JSON block from text for clean markdown display
          cleanText = rawText.replace(/```(?:json)?[\s\S]*?```/, '').trim()
        }
      } catch (e) {
        console.warn('Failed to parse proposal JSON from Gemini text:', e)
      }
    } else {
      // Fallback: check if un-fenced JSON object is present
      const rawJsonMatch = rawText.match(/(\{[\s\r\n]*"isCampaignProposal"[\s\S]*\})\s*$/)
      if (rawJsonMatch) {
        try {
          const parsed = JSON.parse(rawJsonMatch[1])
          if (parsed.isCampaignProposal && parsed.campaign) {
            proposalData = parsed.campaign
            cleanText = rawText.replace(rawJsonMatch[1], '').trim()
          }
        } catch (e) {
          // Ignore
        }
      }
    }

    return NextResponse.json({
      success: true,
      text: cleanText,
      proposal: proposalData
    })
  } catch (error: any) {
    console.error('[Campaign AI Chat] Error:', error)
    return NextResponse.json({ error: error.message || 'Internal server error' }, { status: 500 })
  }
}
